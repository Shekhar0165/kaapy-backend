import { Prop, Schema, SchemaFactory } from '@nestjs/mongoose';
import { HydratedDocument, Types } from 'mongoose';
import { ENABLED_LANGUAGES, type LanguageCode } from '../../common/languages.js';

export type TransactionDocument = HydratedDocument<Transaction>;

export enum TransactionType {
  /** The shop gave goods or credit: the customer's balance goes up. */
  GAVE = 'gave',
  /** The shop received money: the customer's balance goes down. */
  GOT = 'got',
}

/** 1,00,00,000 rupees in paise. */
export const MAX_AMOUNT_PAISE = 1_000_000_000;

export const NOTIFICATION_STATUSES = [
  'pending',
  'sms_sent',
  'email_sent',
  'not_delivered',
  'unknown',
  /** The shop turned customer messages off; nothing was or will be sent. */
  'skipped',
] as const;
export type NotificationStatus = (typeof NOTIFICATION_STATUSES)[number];

export const SMS_RESULTS = [
  'sent',
  'no_sim',
  'permission_denied',
  'no_service',
  'radio_off',
  'generic_failure',
  'timeout',
  'unsupported_platform',
  'unknown',
  'limit_exceeded',
  'invalid_number',
  'sim_not_ready',
] as const;
export type SmsResult = (typeof SMS_RESULTS)[number];

@Schema({ _id: false })
export class EntryNotification {
  @Prop({ type: String, enum: NOTIFICATION_STATUSES, required: true, default: 'pending' })
  status!: NotificationStatus;

  /** What the app reported for its SMS attempt; set once (it is the claim marker). */
  @Prop({ type: String, enum: SMS_RESULTS, default: null })
  smsResult!: SmsResult | null;

  /**
   * Raw code from the phone: the Android SmsManager result code, or one of
   * Kaapy's own pre-send check codes (900-999). Diagnostics only.
   */
  @Prop({ type: Number, default: null })
  smsErrorCode!: number | null;

  /** Set only if a delivery report arrives after the SMS was sent. */
  @Prop({ type: Boolean })
  smsDelivered?: boolean;

  @Prop({ type: Boolean, default: false })
  emailSent!: boolean;

  /** Short code only (e.g. "timeout", "rate_limited"), never provider details. */
  @Prop({ type: String, default: null })
  emailError!: string | null;

  @Prop({ type: Date, default: () => new Date() })
  updatedAt!: Date;

  // The shop's message settings when the entry was saved, so the SMS text, any
  // later email fallback and a replay all follow the same choices. Read on the
  // server, never from the client. Missing on older entries (English, note, email).
  @Prop({ type: String, enum: ENABLED_LANGUAGES })
  language?: LanguageCode;

  @Prop({ type: Boolean })
  includeNote?: boolean;

  @Prop({ type: Boolean })
  emailFallback?: boolean;
}

export const EntryNotificationSchema = SchemaFactory.createForClass(EntryNotification);

/**
 * One ledger entry. Append-only: every field is immutable and there are no
 * update or delete routes. Mistakes will be corrected with a reversal entry.
 */
// No `timestamps` option: createdAt is set explicitly by the server, inside the
// same database transaction that moves the balance, and never accepted from a client.
@Schema({ versionKey: false })
export class Transaction {
  @Prop({ type: Types.ObjectId, ref: 'Shop', required: true, index: true, immutable: true })
  shopId!: Types.ObjectId;

  @Prop({ type: Types.ObjectId, ref: 'Customer', required: true, index: true, immutable: true })
  customerId!: Types.ObjectId;

  @Prop({ type: String, required: true, enum: Object.values(TransactionType), immutable: true })
  type!: TransactionType;

  /** Integer paise, > 0. */
  @Prop({
    required: true,
    immutable: true,
    min: 1,
    max: MAX_AMOUNT_PAISE,
    validate: { validator: Number.isInteger, message: 'amount must be an integer number of paise' },
  })
  amount!: number;

  @Prop({ type: String, trim: true, maxlength: 200, default: null, immutable: true })
  note!: string | null;

  /** The customer's balance (integer paise) right after this entry. */
  @Prop({
    required: true,
    immutable: true,
    validate: { validator: Number.isInteger, message: 'balanceAfter must be an integer' },
  })
  balanceAfter!: number;

  /** Server time (UTC) when the entry was saved. */
  @Prop({ type: Date, required: true, immutable: true })
  createdAt!: Date;

  /** Idempotency key generated by the app for this save attempt. */
  @Prop({ type: String, required: true, immutable: true })
  clientRequestId!: string;

  /** Customer notification state: the only part of an entry that may change. */
  @Prop({ type: EntryNotificationSchema, default: () => ({}) })
  notification!: EntryNotification;
}

export const TransactionSchema = SchemaFactory.createForClass(Transaction);

// A retry or double tap with the same key can never create a second entry.
TransactionSchema.index({ shopId: 1, clientRequestId: 1 }, { unique: true });
// Serves the ledger: newest first, with _id as the cursor tiebreaker.
TransactionSchema.index({ shopId: 1, customerId: 1, createdAt: -1, _id: -1 });
// Serves the Balance report: period totals (shopId + createdAt range) and the shop's recent entries.
TransactionSchema.index({ shopId: 1, createdAt: -1, _id: -1 });

// Notification state; also used by the 24h cleanup of stale "pending" entries.
TransactionSchema.index({ 'notification.status': 1, createdAt: 1 });

/** True when an update only $sets fields under `notification.` (nothing else). */
export function touchesOnlyNotification(update: unknown): boolean {
  if (!update || typeof update !== 'object' || Array.isArray(update)) return false;
  const operators = Object.keys(update);
  if (operators.length !== 1 || operators[0] !== '$set') return false;
  const fields = Object.keys((update as { $set: Record<string, unknown> }).$set ?? {});
  return fields.length > 0 && fields.every((field) => field.startsWith('notification.'));
}

// Belt and braces on top of `immutable`: the ledger itself can never be updated
// by query. The only exception is `$set` on `notification.*` fields.
for (const operation of ['updateOne', 'updateMany', 'findOneAndUpdate'] as const) {
  TransactionSchema.pre(operation, function () {
    if (!touchesOnlyNotification(this.getUpdate())) {
      throw new Error('Ledger entries are immutable');
    }
  });
}
for (const operation of ['replaceOne', 'findOneAndReplace'] as const) {
  TransactionSchema.pre(operation, function () {
    throw new Error('Ledger entries are immutable');
  });
}
