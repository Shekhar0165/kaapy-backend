import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  IsBase64,
  IsEnum,
  IsInt,
  IsOptional,
  IsString,
  Length,
  Matches,
  Max,
  MaxLength,
  Min,
} from 'class-validator';
import { NoHtml } from '../../common/validators/no-html.validator.js';
import { TrimString } from '../../common/validation.js';
import {
  MAX_AMOUNT_PAISE,
  NOTIFICATION_STATUSES,
  TransactionType,
} from '../schemas/transaction.schema.js';
import type { NotificationStatus } from '../schemas/transaction.schema.js';

/**
 * Body for a new entry. There is deliberately no date or time field: the
 * server stamps the entry when it is saved, and the global ValidationPipe
 * (forbidNonWhitelisted) rejects a request that sends one.
 */
export class CreateTransactionDto {
  @ApiProperty({ enum: TransactionType, example: TransactionType.GAVE })
  @IsEnum(TransactionType)
  type!: TransactionType;

  @ApiProperty({
    example: 50000,
    minimum: 1,
    maximum: MAX_AMOUNT_PAISE,
    description: 'Integer paise (₹500 = 50000). Max ₹1,00,00,000.',
  })
  // Decimals (500.5), zero and negatives fail; paise are always whole numbers.
  @IsInt({ message: 'amount must be a whole number of paise' })
  @Min(1, { message: 'amount must be greater than 0' })
  @Max(MAX_AMOUNT_PAISE, { message: 'amount cannot exceed ₹1,00,00,000' })
  amount!: number;

  @ApiPropertyOptional({ example: 'Rice 5 kg, cooking oil', maxLength: 200 })
  @TrimString({ emptyAsUndefined: true })
  @IsOptional()
  @IsString()
  @MaxLength(200)
  @NoHtml()
  note?: string;

  @ApiProperty({
    example: '7f2c1d9e-4b6a-4c8e-9a1f-2d3e4f5a6b7c',
    description: 'Generated by the app per entry; resending it returns the original entry.',
  })
  @IsString()
  @Length(8, 64)
  @Matches(/^[A-Za-z0-9-]+$/, { message: 'clientRequestId may only contain letters, digits and -' })
  clientRequestId!: string;
}

export class ListTransactionsQueryDto {
  @ApiPropertyOptional({ minimum: 1, maximum: 100, default: 30 })
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(100)
  limit?: number;

  @ApiPropertyOptional({ description: 'nextCursor from the previous page' })
  @IsOptional()
  @IsString()
  @MaxLength(200)
  @IsBase64({ urlSafe: true }, { message: 'cursor is invalid' })
  cursor?: string;
}

export class EntryNotificationDto {
  @ApiProperty({ enum: NOTIFICATION_STATUSES, example: 'pending' })
  status!: NotificationStatus;

  @ApiProperty({ description: 'True once a delivery report arrived for the SMS' })
  smsDelivered!: boolean;
}

export class TransactionResponseDto {
  @ApiProperty({ example: '6710c0ffee0000000000beef' })
  id!: string;

  @ApiProperty({ example: '6710c0ffee0000000000abcd' })
  customerId!: string;

  @ApiProperty({ enum: TransactionType })
  type!: TransactionType;

  @ApiProperty({ example: 50000, description: 'Integer paise' })
  amount!: number;

  @ApiProperty({ type: String, nullable: true, example: 'Rice 5 kg' })
  note!: string | null;

  @ApiProperty({ example: 515000, description: "Customer's balance in paise right after this entry" })
  balanceAfter!: number;

  @ApiProperty({ type: String, format: 'date-time', description: 'Server time (UTC)' })
  createdAt!: Date;

  @ApiProperty({ type: EntryNotificationDto })
  notification!: EntryNotificationDto;
}

export class CreateTransactionResponseDto {
  @ApiProperty({ type: TransactionResponseDto })
  transaction!: TransactionResponseDto;

  @ApiProperty({ example: 515000, description: "The customer's current balance in paise" })
  balance!: number;

  @ApiProperty({
    example: 'Sharma General Store: Rs.500 added to your khata (Tea) on 14 Oct 2026, 11:43 AM. Total due: Rs.5,150.',
    type: String,
    nullable: true,
    description:
      'Notification text built by the server; the app sends exactly this by SMS. ' +
      "null when the shop turned customer messages off (notification.status is 'skipped').",
  })
  messageText!: string | null;

  @ApiProperty({ example: '+919876543210', description: 'Where the app sends the SMS' })
  customerPhone!: string;

  @ApiProperty({ description: 'Whether an email fallback is possible' })
  hasEmail!: boolean;
}

export class TransactionListResponseDto {
  @ApiProperty({ type: [TransactionResponseDto] })
  items!: TransactionResponseDto[];

  @ApiProperty({ type: String, nullable: true, description: 'Pass as ?cursor= for the next page' })
  nextCursor!: string | null;

  @ApiProperty({ example: 515000, description: "The customer's current balance in paise" })
  balance!: number;
}
